import 'package:flutter_test/flutter_test.dart';
import 'package:lampada/features/daily_cards/domain/split_course_text.dart';

void main() {
  test('каждое предложение становится отдельной карточкой', () {
    expect(
      splitCourseText(
        'Первое предложение. Второе предложение! Третье предложение?',
      ),
      ['Первое предложение. ', 'Второе предложение! ', 'Третье предложение?'],
    );
  });
  test('короткое предложение объединяется со следующим', () {
    expect(splitCourseText('Да. Следующее предложение.'), [
      'Да. Следующее предложение.',
    ]);
  });
  test('ровно 10 символов недостаточно для отдельной карточки', () {
    expect(splitCourseText('123456789.   Следующее предложение.'), [
      '123456789.   Следующее предложение.',
    ]);
  });
  test('11 символов достаточно для отдельной карточки', () {
    expect(splitCourseText('1234567890. Следующее предложение.'), [
      '1234567890. ',
      'Следующее предложение.',
    ]);
  });
  test('короткий остаток объединяется с предыдущей карточкой', () {
    for (final ending in ['Да.', 'Да']) {
      final text = 'Первое предложение. Второе предложение. $ending';
      expect(splitCourseText(text), [
        'Первое предложение. ',
        'Второе предложение. $ending',
      ]);
    }
  });
  test('несколько коротких предложений не теряют текст и переносы', () {
    const text = 'Да.\nНет!\n\nАминь.';
    expect(splitCourseText(text), ['Да.\nНет!\n\nАминь.']);
  });
  test('unicode считается по символам, а не единицам UTF-16', () {
    const text = '🙏🙏🙏🙏🙏. Следующее предложение.';
    expect(splitCourseText(text), [text]);
  });
  test('перенос внутри предложения не разрывает его', () {
    expect(splitCourseText('Первая строка\nпродолжается\n\nи заканчивается.'), [
      'Первая строка\nпродолжается\n\nи заканчивается.',
    ]);
  });
  test('перенос между предложениями сохраняется', () {
    const text = 'Первое предложение.\n\nВторое предложение.';
    expect(splitCourseText(text), [
      'Первое предложение.\n\n',
      'Второе предложение.',
    ]);
  });
  test('длинное предложение остаётся целым', () {
    final text = '${List.filled(60, 'Слово').join(' ')}.';
    expect(splitCourseText(text), [text]);
  });
  test('закрывающие кавычки и многоточие относятся к предложению', () {
    const text = 'Он сказал: «Читайте!» Потом задумался… И продолжил.';
    expect(splitCourseText(text), [
      'Он сказал: «Читайте!» ',
      'Потом задумался… ',
      'И продолжил.',
    ]);
  });
  test('сокращения и десятичные числа не заканчивают предложение', () {
    const text = 'Св. Иоанн писал об этом, т. е. пояснял мысль. Число 3.14.';
    expect(splitCourseText(text), [
      'Св. Иоанн писал об этом, т. е. пояснял мысль. ',
      'Число 3.14.',
    ]);
  });
  test('текст без знака конца и unicode сохраняются', () {
    expect(splitCourseText('Тема 🙏'), ['Тема 🙏']);
    expect(splitCourseText(''), ['']);
  });
}
