/// Быстрая, платформенная проверка: есть ли у устройства сетевой интерфейс.
///
/// Это не проверка доступности конкретного сайта: при Wi-Fi с captive portal
/// сетевой запрос всё равно должен обработать таймаут или ошибку сам.
abstract interface class NetworkStatus {
  Future<bool> isOnline();
}
