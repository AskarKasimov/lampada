import '../../../../core/result/result.dart';

/// Прогресс юзера по курсу «Основы веры».
///
/// Курс сдвигает «Основы» с календаря на личный прогресс: у двух юзеров в
/// один день будут разные темы. Это сознательное отступление от §5
/// требований («все карточки дня календарные») — оно и есть тот путь от
/// простого к сложному, который требования обещали, но вычеркнули вместе с
/// движком «Путь». Азбука такой путь уже собрала, мы лишь перестаём входить
/// в него с середины.
abstract interface class CourseProgressRepository {
  /// Номер темы, которую юзер должен увидеть сейчас. Новый юзер — тема 1.
  Future<Result<int>> currentTopic();

  /// Отмечает текущую тему прочитанной сегодня. Сама тема меняется только
  /// при следующем вызове [currentTopic] в новый календарный день.
  Future<Result<void>> markCurrentTopicRead();
}
