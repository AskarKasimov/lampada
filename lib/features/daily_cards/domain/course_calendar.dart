/// Перевод номера темы курса «Основы веры» в дату, под которой эта
/// тема лежит на Азбуке.
///
/// Азбука публикует «Основы» как годовой курс и привязывает тему к дню года:
/// проверено на пяти датах — 2 января это Тема 2, 5 марта Тема 64, 20 мая
/// Тема 140, 28 июля Тема 209, 11 ноября Тема 315. Совпадение точное, без
/// сдвигов.
///
/// Отсюда и вся механика курса: чтобы показать Тему K, достаточно запросить
/// день, у которого день года равен K. Отдельного эндпоинта по номеру темы у
/// Азбуки нет, а этот есть и уже реализован.
library;

/// Опорный год — невисокосный, чтобы номера тем были ровно 1..[topicCount].
/// В високосном появился бы 366-й день, которому не соответствует тема.
/// Страницы прошлых лет Азбука отдаёт бессрочно, так что год фиксированный:
/// одна и та же тема всегда приезжает по одной и той же дате.
const _referenceYear = 2026;

/// Сколько тем в курсе.
const courseTopicCount = 365;

/// Дата, под которой на Азбуке лежит тема [number] (1..[courseTopicCount]).
DateTime dateForCourseTopic(int number) =>
    DateTime(_referenceYear, 1, normalizeCourseTopic(number));

/// Курс конечный: некорректный номер не должен начинать его заново.
int normalizeCourseTopic(int number) => number.clamp(1, courseTopicCount);
