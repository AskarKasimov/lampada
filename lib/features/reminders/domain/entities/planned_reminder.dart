import '../../../daily_cards/domain/entities/day_card.dart';

/// Одно запланированное напоминание.
class PlannedReminder {
  const PlannedReminder({
    required this.id,
    required this.at,
    required this.title,
    required this.body,
  });

  /// Стабильный идентификатор для отмены в системе уведомлений.
  final int id;
  final DateTime at;
  final String title;
  final String body;

  @override
  String toString() => 'PlannedReminder($id, $at, "$title")';
}

