/// Одно запланированное напоминание.
class PlannedReminder {
  const PlannedReminder({
    required this.id,
    required this.at,
    required this.title,
    required this.body,
    this.section = DaySection.wisdom,
  });

  /// Стабильный идентификатор для отмены в системе уведомлений.
  final int id;
  final DateTime at;
  final String title;
  final String body;

  /// Куда ведёт нажатие на напоминание.
  final DaySection section;

  @override
  String toString() => 'PlannedReminder($id, $at, "$title")';
}

